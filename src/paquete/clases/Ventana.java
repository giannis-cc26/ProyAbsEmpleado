    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String nom = this.jTextField1.getText();
        String dire = this.jTextField2.getText();
        float sueldoB = Float.parseFloat(this.jTextField3.getText());
        
        if (this.jRadioButton1.isSelected())
        {
            String cargo = this.jTextField4.getText();
            Administrativo ref = new Administrativo(cargo, 'A', nom, dire, sueldoB);
            ref.CalcularBono();
            ref.CalcularSueldoP();
            GE.Ingresar(ref);
        }
        else if (this.jRadioButton2.isSelected())
        {
            int anti = Integer.parseInt(this.jTextField5.getText());
            Electronico ref = new Electronico(anti, 'E', nom, dire, sueldoB);
            ref.CalcularBono();
            ref.CalcularSueldoP();
            GE.Ingresar(ref);
        }
        else
        {
            String espe = this.jTextField6.getText();
            int grado = Integer.parseInt(this.jTextField7.getText());
            Programador ref = new Programador(espe, grado, 'P', nom, dire, sueldoB);
            ref.CalcularBono();
            ref.CalcularSueldoP();
            GE.Ingresar(ref);
        }
        
        CargarTabla();
    }//GEN-LAST:event_jButton1ActionPerformed

